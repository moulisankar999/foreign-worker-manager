import { printPage } from '../lib/platform'
import { useLiveQuery } from 'dexie-react-hooks'
import { useEffect } from 'react'
import { useNavigate, useParams } from 'react-router-dom'
import { db } from '../lib/db'
import { LogoImg } from '../components/logos'
import { outletLogo } from '../lib/logos'
import { outletName } from '../lib/calc'
import { useOutlets, useSettings } from '../lib/hooks'
import { useAuth } from '../lib/auth'
import { useConfig } from '../lib/config'
import { computePayslip, monthLabel } from '../lib/pay'
import { fmtDate, rm } from '../lib/util'

export default function PayslipPrint() {
  const { wid, pid } = useParams()
  const w = useLiveQuery(() => db.workers.get(wid || ''), [wid])
  const s = useSettings()
  const outlets = useOutlets()
  const cfg = useConfig()
  const { canSeeSalary } = useAuth()
  const nav = useNavigate()
  useEffect(() => { document.title = 'Payslip — Foreign Worker Manager' }, [])
  if (w === undefined) return <p>Loading…</p>
  const p = w?.payslips?.find((x) => x.id === pid)
  if (!w || !p || !canSeeSalary) return <p>Payslip not found. <button onClick={() => nav('/')}>Home</button></p>
  const r = computePayslip(p, cfg.rates, w)
  const line = (k: string, v: number | undefined, always = false) => (v || always ? <tr><th>{k}</th><td className="num">{rm(v || 0)}</td></tr> : null)
  return (
    <div className="print-wrap">
      <div className="no-print print-bar">
        <button className="btn btn-secondary" onClick={() => nav(`/workers/${w.id}`)}>← Back</button>
        <button className="btn btn-primary" onClick={() => printPage()}>🖨 Print / Save PDF</button>
      </div>
      <article className="memo">
        <header className="memo-h">
          <div className="row gap-s"><LogoImg path={outletLogo(outlets.find((o) => o.id === w.outletId))} size={48} fallback={false} /><div><h1>{s.companyName}</h1><p>{outletName(outlets, w.outletId)}</p></div></div>
          <div className="memo-k"><h2>PAYSLIP</h2><p>{monthLabel(p.month)}</p><p>Paid: {p.payDate ? fmtDate(p.payDate) : '__________'}</p></div>
        </header>
        <table className="memo-t"><tbody>
          <tr><th>Name</th><td>{w.fullName}</td><th>Worker ID</th><td>{w.workerNo}</td></tr>
          <tr><th>Position</th><td>{w.jobCategory || '—'}</td><th>Joined</th><td>{fmtDate(w.joinDate)}</td></tr>
          <tr><th>Daily rate</th><td>{rm(r.orpDaily)}</td><th>Hourly rate</th><td>{rm(r.orpHourly)}</td></tr>
        </tbody></table>
        <div className="grid2 slip-cols">
          <div>
            <h3>Earnings</h3>
            <table className="memo-t"><tbody>
              {line(`Basic pay${p.unpaidDays ? ` (less ${p.unpaidDays} unpaid day(s))` : ''}`, r.basicEarned, true)}
              {line('Allowances', p.allowances)}{line('Other earnings', p.otherEarnings)}
              {line(`Overtime — normal (${p.otNormalH || 0} h)`, r.otNormal)}{line('Rest day worked', r.restDay)}{line(`Overtime — rest day (${p.otRestH || 0} h)`, r.restOt)}
              {line(`Public holiday worked (${p.phDays || 0} day(s))`, r.phDay)}{line(`Overtime — public holiday (${p.otPhH || 0} h)`, r.phOt)}
              <tr className="tot"><th>Gross wages</th><td className="num">{rm(r.gross)}</td></tr>
            </tbody></table>
          </div>
          <div>
            <h3>Deductions</h3>
            <table className="memo-t"><tbody>
              {line('EPF (worker)', r.epfEe)}{line('PERKESO (worker)', r.socsoEe)}{line('LINDUNG 24 Jam', r.lindung)}
              {line('Accommodation', p.hostel)}{line('Salary advance', p.advance)}{line('Loan repayment', p.loanRepay)}{line('Other', p.otherDeductions)}
              <tr className="tot"><th>Total deductions</th><td className="num">{rm(r.gross - r.net)}</td></tr>
            </tbody></table>
          </div>
        </div>
        <table className="memo-t slip-net"><tbody><tr className="tot"><th>NET PAY</th><td className="num">{rm(r.net)}</td></tr></tbody></table>
        <h3>Employer contributions</h3>
        <table className="memo-t"><tbody>
          <tr><th>EPF (employer)</th><td className="num">{rm(r.epfEr)}</td><th>PERKESO (employer)</th><td className="num">{rm(r.socsoEr)}</td></tr>
        </tbody></table>
        {p.notes && <p><strong>Notes:</strong> {p.notes}</p>}
        <div className="signs">
          {[['Received by (worker)', w.fullName], ['Prepared by', p.savedBy || '']].map(([k, v]) => (
            <div key={k}><div className="sline" /><strong>{k}</strong><span>{v || 'Name:'}</span><span>Date:</span></div>
          ))}
        </div>
        <footer className="memo-f">Generated by Foreign Worker Manager · {fmtDate(new Date().toISOString().slice(0, 10))} · Contributions follow the rates in the app; PERKESO amounts may differ slightly from PERKESO’s table.</footer>
      </article>
    </div>
  )
}
