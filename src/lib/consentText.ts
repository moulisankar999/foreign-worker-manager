/** languages with a built-in translation (Malay is the long-standing default second language) */
export const TRANSLATED = Object.keys(CONSENT_TR).filter((k) => k !== 'ms')

export interface ConsentOverride { text: Partial<ConsentText>; checked?: boolean; checkedBy?: string; updatedAt?: string; updatedBy?: string }
export interface ConsentTranslationsConfig { items: Record<string, ConsentOverride> }
export const DEFAULT_CONSENT_TRANSLATIONS: ConsentTranslationsConfig = { items: {} }

/** the second language on a worker's consent form, and why */
export function consentLanguage(primary: string | undefined, overrides: ConsentTranslationsConfig): { code: string; text: ConsentText; fallback?: string; override?: ConsentOverride } {
  const ms = { ...CONSENT_TR.ms, ...clean(overrides.items?.ms?.text) }
  if (!primary) return { code: 'ms', text: ms, fallback: 'Primary language not recorded — English + Bahasa Malaysia used.' }
  if (primary === 'en' || primary === 'ms') return { code: 'ms', text: ms, override: overrides.items?.ms }
  const ov = overrides.items?.[primary]
  const base = CONSENT_TR[primary]
  if (!base) {
    // a language without a built-in translation can still be used once every field has been typed in Settings
    if (ov && CONSENT_KEYS.every((k) => (ov.text?.[k] || '').trim())) return { code: primary, text: { ...CONSENT_EN, ...clean(ov.text) } as ConsentText, override: ov }
    return { code: 'ms', text: ms, fallback: 'No translation for the worker\u2019s language yet — English + Bahasa Malaysia used.' }
  }
  return { code: primary, text: { ...base, ...clean(ov?.text) }, override: ov }
}
function clean(t?: Partial<ConsentText>): Partial<ConsentText> {
  const o: Partial<ConsentText> = {}
  for (const k of CONSENT_KEYS) { const v = t?.[k]; if (typeof v === 'string' && v.trim()) o[k] = v.trim() }
  return o
}
