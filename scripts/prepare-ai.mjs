// Copies the app's Help/FAQ and request types into the ai-assistant Edge Function as plain JSON,
// so the assistant answers "how do I…" from the same text as the in-app Help page. Run before deploying the function.
import fs from 'node:fs'
import { createRequire } from 'node:module'
const require = createRequire(new URL('../package.json', import.meta.url))
const ts = require('typescript')
const root = new URL('..', import.meta.url)
const load = async (rel) => {
  const src = fs.readFileSync(new URL(rel, root), 'utf8')
  const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText
  const tmp = `/tmp/prep-ai-${process.pid}-${rel.replace(/\W/g, '_')}.mjs`
  fs.writeFileSync(tmp, js)
  try { return await import(tmp) } finally { fs.unlinkSync(tmp) }
}
const help = await load('src/help/content.ts')
const wf = await load('src/lib/workflow.ts')
const out = {
  note: 'AUTO-GENERATED by scripts/prepare-ai.mjs from src/help/content.ts and src/lib/workflow.ts — edit those, not this file',
  guides: help.GUIDES.map((g) => ({ id: g.id, group: g.group, title: g.title, roles: g.roles, text: [g.intro, ...(g.steps || []).map((s, i) => `${i + 1}. ${s}`), g.tip && `Tip: ${g.tip}`, g.important && `Important: ${g.important}`].filter(Boolean).join('\n') })),
  faqs: help.FAQS.map((f) => ({ q: f.q, a: f.a, roles: f.roles })),
  requestTypes: wf.REQUEST_TYPES.map((t) => ({ key: t.key, label: t.label, group: t.group, level: t.level, amountKey: t.amountKey || null,
    fields: (t.fields || []).map((f) => ({ key: f.key, label: f.label, type: f.type || 'text', required: !!f.required, options: f.options || undefined })) })),
}
fs.writeFileSync(new URL('supabase/functions/ai-assistant/knowledge.json', root), JSON.stringify(out))
console.log(`prepared ai-assistant/knowledge.json: ${out.guides.length} guides, ${out.faqs.length} FAQs, ${out.requestTypes.length} request types`)
