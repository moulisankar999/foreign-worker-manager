// Placeholder documents for the SAMPLE data (Approval & Recruitment). Every file is clearly fake:
// a big "SAMPLE – NOT A REAL DOCUMENT" watermark, fictitious names and numbers, and a plain generic layout
// (no crests, emblems, MRZ lines or government formats). Photos are neutral drawn avatars, not real people.
import { createRequire } from 'node:module'
const require = createRequire(new URL('../../package.json', import.meta.url))
const { PDFDocument, StandardFonts, rgb, degrees } = require('pdf-lib')
const sharp = require('sharp')

const PALETTE = ['#cfe3f5', '#d8f0dc', '#f6e3c8', '#e7dcf5', '#f5d6dc', '#d6eef0', '#ece8d4']

/** Neutral avatar: a grey head-and-shoulders silhouette on a soft colour, with "SAMPLE" across it. */
export function avatarSvg(seed = 0) {
  const bg = PALETTE[Math.abs(seed) % PALETTE.length]
  return `<svg xmlns="http://www.w3.org/2000/svg" width="240" height="300" viewBox="0 0 240 300">
<rect width="240" height="300" fill="${bg}"/>
<circle cx="120" cy="112" r="52" fill="#8a94a3"/>
<path d="M28 300 C 34 220, 80 186, 120 186 C 160 186, 206 220, 212 300 Z" fill="#8a94a3"/>
<rect x="0" y="246" width="240" height="40" fill="#ffffff" fill-opacity="0.82"/>
<text x="120" y="274" font-family="Helvetica, Arial, sans-serif" font-size="24" font-weight="700" fill="#c0392b" text-anchor="middle">SAMPLE</text>
</svg>`
}
export async function avatarPng(seed = 0, width = 240) {
  return sharp(Buffer.from(avatarSvg(seed))).resize({ width }).png().toBuffer()
}
export async function avatarDataUrl(seed = 0) {
  return 'data:image/png;base64,' + (await avatarPng(seed, 160)).toString('base64')
}

const TITLES = {
  passport: 'Sample passport details (fictitious)',
  stamped: 'Sample passport with visa page (fictitious)',
  vdr: 'Sample calling visa (VDR) approval (fictitious)',
  letter: 'Sample quota approval letter (fictitious)',
  medical: 'Sample medical report (fictitious)',
  cmo: 'Sample Check Out Memo (COM) (fictitious)',
  ticket: 'Sample air ticket (fictitious)',
  hr_ack: 'Sample HR briefing acknowledgement (fictitious)',
  photo: 'Sample worker photo (fictitious)',
  fomema: 'Sample FOMEMA medical result (fictitious)',
  ssm: 'Sample company registration record (fictitious)',
  director_id: 'Sample director identity card copy (fictitious)',
}

/**
 * @param {keyof typeof TITLES} kind
 * @param {Array<[string, string]>} fields label/value rows (all fictitious)
 * @param {{ photoSeed?: number, note?: string }} [o]
 */
export async function samplePdf(kind, fields, o = {}) {
  const doc = await PDFDocument.create()
  doc.setTitle(`SAMPLE – ${TITLES[kind] || kind}`); doc.setSubject('SAMPLE – NOT A REAL DOCUMENT'); doc.setProducer('FW Manager sample data')
  const page = doc.addPage([595, 842]) // A4
  const f = await doc.embedFont(StandardFonts.Helvetica), b = await doc.embedFont(StandardFonts.HelveticaBold)
  const red = rgb(0.75, 0.16, 0.13), ink = rgb(0.15, 0.17, 0.2), grey = rgb(0.45, 0.48, 0.52)
  // header band
  page.drawRectangle({ x: 0, y: 772, width: 595, height: 70, color: rgb(0.93, 0.94, 0.95) })
  page.drawText('SAMPLE DOCUMENT – FOR TRAINING AND DEMONSTRATION ONLY', { x: 40, y: 812, size: 11, font: b, color: red })
  page.drawText(TITLES[kind] || kind, { x: 40, y: 788, size: 18, font: b, color: ink })
  let y = 740
  let photoW = 0
  if (o.photoSeed !== undefined) {
    const img = await doc.embedPng(await avatarPng(o.photoSeed))
    photoW = 130
    page.drawRectangle({ x: 425, y: y - 162, width: 130, height: 162, borderColor: grey, borderWidth: 1 })
    page.drawImage(img, { x: 426, y: y - 161, width: 128, height: 160 })
    page.drawText('Drawn avatar – not a real person', { x: 425, y: y - 176, size: 7.5, font: f, color: grey })
  }
  for (const [k, v] of fields) {
    page.drawText(k, { x: 40, y, size: 9, font: f, color: grey })
    page.drawText(String(v ?? '–'), { x: 190, y, size: 11, font: b, color: ink, maxWidth: 360 - (photoW ? 140 : 0) })
    page.drawLine({ start: { x: 40, y: y - 8 }, end: { x: 555 - (photoW && y > 560 ? 140 : 0), y: y - 8 }, thickness: 0.4, color: rgb(0.85, 0.86, 0.88) })
    y -= 30
  }
  if (o.note) { y -= 10; if (photoW) y = Math.min(y, 540); page.drawText(o.note, { x: 40, y, size: 10, font: f, color: ink, maxWidth: 515, lineHeight: 14 }) }
  // footer
  page.drawLine({ start: { x: 40, y: 92 }, end: { x: 555, y: 92 }, thickness: 0.6, color: grey })
  page.drawText('All names, numbers and dates on this page are fictitious. This page was generated by FW Manager as sample data.', { x: 40, y: 76, size: 8.5, font: f, color: grey })
  page.drawText('It is not issued by any government, embassy, agency or employer and must not be used for any official purpose.', { x: 40, y: 64, size: 8.5, font: f, color: grey })
  page.drawText('Remove all sample data in Settings > Data > Remove sample data.', { x: 40, y: 52, size: 8.5, font: f, color: grey })
  // big watermark (drawn last so it sits on top)
  for (const [x, yy] of [[60, 200], [60, 480]]) {
    page.drawText('SAMPLE – NOT A REAL DOCUMENT', { x, y: yy, size: 32, font: b, color: red, opacity: 0.28, rotate: degrees(30) })
  }
  page.drawText('SAMPLE', { x: 130, y: 330, size: 110, font: b, color: red, opacity: 0.1, rotate: degrees(30) })
  return Buffer.from(await doc.save())
}
